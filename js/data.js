// Hàm tính toán tự động các khoản lương, bảo hiểm, thuế TNCN theo luật Việt Nam
function calculateSalaryRecord(raw) {
    const standardDays = raw.standardWorkDays || 26;
    const workDays = raw.workDays !== undefined ? raw.workDays : 26;
    const baseSalary = raw.baseSalary || 0;
    
    // Lương theo ngày công thực tế
    const workdaySalary = raw.workdaySalary !== undefined 
        ? raw.workdaySalary 
        : Math.round((baseSalary / standardDays) * workDays);

    const allowanceResponsibility = raw.allowanceResponsibility || 0;
    const allowanceMeal = raw.allowanceMeal || 0;
    const allowanceFuel = raw.allowanceFuel || 0;
    const allowancePhone = raw.allowancePhone || 0;
    const bonusKPI = raw.bonusKPI || 0;
    const overtimePay = raw.overtimePay || 0;

    // Tổng thu nhập (Thu nhập gộp - Gross)
    const totalIncome = raw.totalIncome !== undefined 
        ? raw.totalIncome 
        : (workdaySalary + allowanceResponsibility + allowanceMeal + allowanceFuel + allowancePhone + bonusKPI + overtimePay);

    // Mức đóng bảo hiểm (thường theo lương đóng BHXH, trần 36tr theo lương cơ sở 1.8tr x 20)
    const insBase = Math.min(raw.insuranceBase || baseSalary, 36000000);
    const rBHXH = (window.COMPANY_INFO && window.COMPANY_INFO.rateBHXH !== undefined ? window.COMPANY_INFO.rateBHXH : 8) / 100;
    const rBHYT = (window.COMPANY_INFO && window.COMPANY_INFO.rateBHYT !== undefined ? window.COMPANY_INFO.rateBHYT : 1.5) / 100;
    const rBHTN = (window.COMPANY_INFO && window.COMPANY_INFO.rateBHTN !== undefined ? window.COMPANY_INFO.rateBHTN : 1) / 100;

    const insuranceBHXH = raw.insuranceBHXH !== undefined ? raw.insuranceBHXH : Math.round(insBase * rBHXH);
    const insuranceBHYT = raw.insuranceBHYT !== undefined ? raw.insuranceBHYT : Math.round(insBase * rBHYT);
    const insuranceBHTN = raw.insuranceBHTN !== undefined ? raw.insuranceBHTN : Math.round(Math.min(insBase, 99200000) * rBHTN);
    const unionFee = raw.unionFee !== undefined ? raw.unionFee : 0;
    const advancePayment = raw.advancePayment || 0;

    // Tính thuế TNCN nếu chưa định nghĩa sẵn
    let taxTNCN = raw.taxTNCN;
    if (taxTNCN === undefined) {
        // Thu nhập chịu thuế = Tổng thu nhập - Các khoản phụ cấp miễn thuế (ăn trưa 730k, trang phục/xăng xe điện thoại theo quy chế)
        const exemptAllowances = Math.min(allowanceMeal, 730000) + allowancePhone;
        const taxableIncome = Math.max(0, totalIncome - exemptAllowances);
        
        // Giảm trừ: Bản thân 11tr + Người phụ thuộc 4.4tr/người + Bảo hiểm bắt buộc
        const dependents = raw.dependents || 0;
        const totalDeductionForTax = 11000000 + (dependents * 4400000) + insuranceBHXH + insuranceBHYT + insuranceBHTN;
        const assessableIncome = Math.max(0, taxableIncome - totalDeductionForTax);

        // Biểu thuế lũy tiến từng phần
        if (assessableIncome <= 0) {
            taxTNCN = 0;
        } else if (assessableIncome <= 5000000) {
            taxTNCN = Math.round(assessableIncome * 0.05);
        } else if (assessableIncome <= 10000000) {
            taxTNCN = Math.round(assessableIncome * 0.1 - 250000);
        } else if (assessableIncome <= 18000000) {
            taxTNCN = Math.round(assessableIncome * 0.15 - 750000);
        } else if (assessableIncome <= 32000000) {
            taxTNCN = Math.round(assessableIncome * 0.2 - 1650000);
        } else if (assessableIncome <= 52000000) {
            taxTNCN = Math.round(assessableIncome * 0.25 - 3250000);
        } else if (assessableIncome <= 80000000) {
            taxTNCN = Math.round(assessableIncome * 0.3 - 5850000);
        } else {
            taxTNCN = Math.round(assessableIncome * 0.35 - 9850000);
        }
    }

    const totalDeduction = raw.totalDeduction !== undefined 
        ? raw.totalDeduction 
        : (insuranceBHXH + insuranceBHYT + insuranceBHTN + unionFee + taxTNCN + advancePayment);

    const netSalary = raw.netSalary !== undefined 
        ? raw.netSalary 
        : (totalIncome - totalDeduction);

    return {
        ...raw,
        standardWorkDays: standardDays,
        workDays,
        baseSalary,
        workdaySalary,
        allowanceResponsibility,
        allowanceMeal,
        allowanceFuel,
        allowancePhone,
        bonusKPI,
        overtimePay,
        totalIncome,
        insuranceBHXH,
        insuranceBHYT,
        insuranceBHTN,
        unionFee,
        taxTNCN,
        advancePayment,
        totalDeduction,
        netSalary
    };
}

